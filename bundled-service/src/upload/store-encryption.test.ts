import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes } from 'node:crypto';
import { afterEach, expect, it } from 'vitest';
import { UploadStore } from './store';
const dirs: string[] = [];
afterEach(() => { for (const dir of dirs) rmSync(dir, { recursive: true, force: true }); dirs.length = 0; });
const content = '#EXTM3U\n#EXTINF:-1,ch1\nhttp://host/live/user1/synthetic-secret/1';
it('protects stream URLs while leaving channel tags and metadata unencrypted', () => {
  const dir = mkdtempSync(join(tmpdir(), 'iptv-sealed-')); dirs.push(dir);
  const legacy = new UploadStore(dir); legacy.save('list1', content);
  const key = randomBytes(32).toString('base64');
  const store = new UploadStore(dir, true);
  expect(() => store.read('list1')).toThrow();
  store.unlock(key);
  expect(store.read('list1')).toBe(content);
  expect(readFileSync(join(dir, 'list1.m3u'), 'utf8')).not.toContain('synthetic-secret');
  expect(readFileSync(join(dir, 'list1.json'), 'utf8')).toContain('list1');
  expect(readFileSync(join(dir, 'list1.m3u'), 'utf8')).toContain('#EXTINF:-1,ch1');
  const restarted = new UploadStore(dir, true); restarted.unlock(key);
  expect(restarted.list()[0].id).toBe('list1');
  expect(restarted.read('list1')).toBe(content);
  restarted.save('list2', content);
  expect(readFileSync(join(dir, 'list2.m3u'), 'utf8')).not.toContain('synthetic-secret');
});
it('rejects wrong keys and modified ciphertext without overwriting files', () => {
  const dir = mkdtempSync(join(tmpdir(), 'iptv-sealed-')); dirs.push(dir);
  const store = new UploadStore(dir, true); const key = randomBytes(32).toString('base64');
  store.unlock(key); store.save('list1', content);
  const file = join(dir, 'list1.m3u'); const original = readFileSync(file, 'utf8');
  expect(() => new UploadStore(dir, true).unlock(randomBytes(32).toString('base64'))).toThrow();
  expect(readFileSync(file, 'utf8')).toBe(original);
  const token = original.match(/IPTV-URL1:([A-Za-z0-9+/]+=*)/)![1];
  const encrypted = JSON.parse(Buffer.from(token, 'base64').toString('utf8'));
  encrypted.data = 'AAAA' + encrypted.data.slice(4);
  writeFileSync(file, original.replace(token, Buffer.from(JSON.stringify(encrypted)).toString('base64')));
  expect(() => store.read('list1')).toThrow();
});
